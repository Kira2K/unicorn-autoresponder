import type { Client, MessagePlan } from "./policy.ts";
import type { ClientMessageConfig } from "./message-config.mts";
/** Fixed plain-text product templates from TAS-143; no model or paraphrasing. */
export function messageText(
  client: Client,
  plan: Extract<MessagePlan, { kind: "send" }>,
  config: ClientMessageConfig,
): string {
  const { instructionsUrl: instructions, hhInstructionsUrl, cabinetUrl: cabinet, cabinetPassword, supportTag } = config;
  if (plan.stage === "reminder")
    return `Привет, ${plan.tag} ! 😊

Напоминаем, что в личном кабинете нужно дополнить несколько данных, которые необходимы команде для работы:

${plan.missing!.map((item) => "— " + item).join("\n")}

Заполнить данные можно здесь: ${cabinet}

Логин — почта, которую ты указал при онбординге.
Пароль — ${cabinetPassword}.

Эта информация поможет нам эффективнее подготовить твоё резюме и организовать поиск вакансий. Будем благодарны, если ты заполнишь недостающие данные в ближайшее время и отпишешься здесь, когда всё будет готово 🙌

Спасибо за помощь! Хорошего вечера 🌸`;
  if (plan.stage === "onboarding")
    return `${plan.tag} привет! Мы очень рады нашему сотрудничеству.

Для начала изучи материалы, которые находятся по ссылке ниже — если потеряешь, всё лежит в закреплённом сообщении здесь.

Здесь в чате можно и нужно задавать все вопросы, которые у тебя возникнут по ходу ${
      client.role === "ученик" ? "обучения" : "нашей совместной работы"
    }. Если вопрос связан с какими-то организационными моментами — тегай ${supportTag}. Тег обязателен, иначе твое сообщение никто не увидит.
${
  client.role === "ученик"
    ? "\n@" +
      client.hardMentor.trim().replace(/^@/, "") +
      " будет твоим ментором по хардам.\n"
    : ""
}
Ниже все, что тебе нужно сделать, чтоб мы начали работу с твоим резюме и легендой${
      client.role === "ученик" ? "" : " перед выходом на рынок"
    }. Очень важно заполнить все личные данные и доступы в личном кабинете (см. инструкцию по онбордингу ниже). Пожалуйста, удели этой задаче время, без данных мы не можем начать работу.

Здесь ты найдешь все необходимые инструкции: ${instructions}
Если при переходе по ссылке ты видишь красный восклицательный знак, просто нажми на proceed anyway.

Твоя папка на Гугл-диске: ${client.googleFolder}
Удачи и хорошего дня!`;
  if (plan.stage === "hh_en process")
    return `${plan.tag} поздравляем с выходом на иностранный рынок!
Теперь тебе нужно создать еще один профиль на платформе headhunter.ru: посмотри, пожалуйста, внимательно эту инструкцию по заполнению hh (${hhInstructionsUrl}) (она помечена как спам, не обращай внимания, все ок).
На этот раз для регистрации необходимо использовать иностранный номер телефона и почту, которые ты сделал для нас на этапе онбординга.
Когда закончишь с созданием, обязательно передай нам доступы, чтобы мы заполнили твой профиль в соответствии с требованиями ATS, для этого внеси креды в личный кабинет (${cabinet}).
Для входа укажи личную почту, которую ты нам передал, пароль - ${cabinetPassword}.
Не забудь, пожалуйста, удостовериться, что ты также передал нам все остальные платформы для откликов — почты, телеграмы, номера телефонов, ссылки на линк и гитхаб. Пожалуйста, внимательно следуй инструкции по созданию хедхантера, это критично важно для того, чтобы мы начали работу с откликами как можно скорее.
Хорошего дня!`;
  return `${plan.tag} поздравляем с переходом на следующий этап!
Сейчас для того чтобы мы начали рассылать отклики от тебя потребуется некоторая вовлеченность.
Для начала тебе нужно создать профиль на платформе headhunter.ru: посмотри, пожалуйста, внимательно эту инструкцию по заполнению hh (${hhInstructionsUrl}) (она помечена как спам, не обращай внимания, все ок).
Обрати внимание, что для регистрации необходимо использовать именно те номера телефонов и почты, которые ты сделал для нас на этапе онбординга.
Когда закончишь с созданием, обязательно передай нам доступы, чтобы мы заполнили твои профили в соответствии с требованиями ATS, для этого внеси креды в личный кабинет (${cabinet}).
Для входа укажи личную почту, которую ты нам передал, пароль - ${cabinetPassword}.
Не забудь, пожалуйста, удостовериться, что ты также передал нам все остальные платформы для откликов — почты, телеграмы, номера телефонов, ссылки на линк, гитхаб и т.д. Пожалуйста, внимательно следуй инструкции по созданию хедхантера, это критично важно для того, чтобы мы начали работу с откликами как можно скорее.
Хорошего дня!`;
}
